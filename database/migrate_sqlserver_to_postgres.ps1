<#
  ย้ายฐานข้อมูล DOCDB จาก SQL Server ไป PostgreSQL
  - สร้างตารางทุกตารางใหม่ใน PostgreSQL (ชื่อเป็นตัวพิมพ์เล็กตามธรรมเนียม PostgreSQL)
  - ข้อความทุกชนิดเป็น citext เพื่อให้เทียบแบบไม่สนตัวพิมพ์เล็ก/ใหญ่เหมือน SQL Server
  - bit -> smallint (โค้ดเดิมเทียบกับ 0/1), datetime -> timestamp, identity -> GENERATED BY DEFAULT AS IDENTITY
  - คัดลอกข้อมูลทุกแถว และตั้งค่า sequence ต่อจากค่าเดิม
  รันซ้ำได้: จะลบตารางใน PostgreSQL แล้วสร้างใหม่ทุกครั้ง

  ตัวอย่าง:
    .\migrate_sqlserver_to_postgres.ps1 -SqlServer "Data Source=(localdb)\MSSQLLocalDB;Initial Catalog=DOCDB;Integrated Security=True" `
        -PgHost localhost -PgDatabase docdb -PgUser csproject -PgPassword <รหัส>
#>
param(
    [string]$SqlServer = "Data Source=(localdb)\MSSQLLocalDB;Initial Catalog=DOCDB;Integrated Security=True",
    [string]$PgHost = "localhost",
    [int]$PgPort = 5432,
    [string]$PgDatabase = "docdb",
    [string]$PgUser = "csproject",
    [Parameter(Mandatory = $true)][string]$PgPassword,
    [string]$Psql = "C:\Program Files\PostgreSQL\17\bin\psql.exe"
)
$ErrorActionPreference = "Stop"

function Q([string]$sql) {
    $c = New-Object System.Data.SqlClient.SqlConnection $SqlServer
    $c.Open()
    try {
        $cmd = $c.CreateCommand(); $cmd.CommandText = $sql
        $dt = New-Object System.Data.DataTable
        (New-Object System.Data.SqlClient.SqlDataAdapter $cmd).Fill($dt) | Out-Null
        return , $dt
    } finally { $c.Close() }
}
function Lit($v, [string]$type) {
    if ($v -is [DBNull] -or $null -eq $v) { return "NULL" }
    switch ($type) {
        { $_ -in "int", "bigint", "smallint", "tinyint", "decimal", "numeric", "float", "real", "money" } { return [string]::Format([Globalization.CultureInfo]::InvariantCulture, "{0}", $v) }
        "bit" { return $(if ($v) { "1" } else { "0" }) }
        { $_ -in "datetime", "datetime2", "smalldatetime", "date" } { return "'" + ([datetime]$v).ToString("yyyy-MM-dd HH:mm:ss.fff", [Globalization.CultureInfo]::InvariantCulture) + "'" }
        default {
            $s = [string]$v
            if ($type -eq "nchar" -or $type -eq "char") { $s = $s.TrimEnd() }
            return "'" + $s.Replace("'", "''") + "'"
        }
    }
}
function PgType([string]$type) {
    switch ($type) {
        "int" { "integer" } "bigint" { "bigint" } "smallint" { "smallint" } "tinyint" { "smallint" }
        "bit" { "smallint" }
        { $_ -in "datetime", "datetime2", "smalldatetime" } { "timestamp" }
        "date" { "date" }
        { $_ -in "decimal", "numeric", "money" } { "numeric" }
        { $_ -in "float", "real" } { "double precision" }
        "uniqueidentifier" { "uuid" }
        default { "citext" }   # nvarchar, varchar, nchar, char, ntext, text
    }
}
function PgDefault([string]$def) {
    if (-not $def) { return "" }
    $d = $def.Trim("(", ")")
    if ($d -match '^(?i)getdate$|^getdate\(\)?$') { return " DEFAULT now()" }
    if ($d -match '^-?\d+$') { return " DEFAULT $d" }
    if ($d -match "^N?'(.*)'$") { return " DEFAULT '" + $Matches[1].Replace("'", "''") + "'" }
    return ""
}

$cols = Q @"
SELECT c.TABLE_NAME, c.COLUMN_NAME, c.DATA_TYPE, c.IS_NULLABLE, c.ORDINAL_POSITION,
       COLUMNPROPERTY(OBJECT_ID(c.TABLE_NAME), c.COLUMN_NAME, 'IsIdentity') AS IsIdentity, c.COLUMN_DEFAULT
FROM INFORMATION_SCHEMA.COLUMNS c JOIN INFORMATION_SCHEMA.TABLES t ON t.TABLE_NAME = c.TABLE_NAME AND t.TABLE_TYPE = 'BASE TABLE'
ORDER BY c.TABLE_NAME, c.ORDINAL_POSITION
"@
$pks = Q @"
SELECT tc.TABLE_NAME, kcu.COLUMN_NAME FROM INFORMATION_SCHEMA.TABLE_CONSTRAINTS tc
JOIN INFORMATION_SCHEMA.KEY_COLUMN_USAGE kcu ON kcu.CONSTRAINT_NAME = tc.CONSTRAINT_NAME
WHERE tc.CONSTRAINT_TYPE = 'PRIMARY KEY' ORDER BY tc.TABLE_NAME, kcu.ORDINAL_POSITION
"@

$out = New-Object System.Text.StringBuilder
[void]$out.AppendLine("-- สร้างโดย migrate_sqlserver_to_postgres.ps1")
[void]$out.AppendLine("SET client_encoding = 'UTF8';")
[void]$out.AppendLine("CREATE EXTENSION IF NOT EXISTS citext;")
[void]$out.AppendLine("BEGIN;")

$tables = $cols.Rows | Group-Object TABLE_NAME
foreach ($t in $tables) {
    $name = $t.Name
    [void]$out.AppendLine("DROP TABLE IF EXISTS $($name.ToLower()) CASCADE;")
    $defs = @()
    foreach ($c in ($t.Group | Sort-Object { [int]$_.ORDINAL_POSITION })) {
        $col = $c.COLUMN_NAME.ToLower()
        if ([int]$c.IsIdentity -eq 1) { $defs += "  $col integer GENERATED BY DEFAULT AS IDENTITY" ; continue }
        $nn = if ($c.IS_NULLABLE -eq "NO") { " NOT NULL" } else { "" }
        $defs += "  $col $(PgType $c.DATA_TYPE)$nn$(PgDefault ([string]$c.COLUMN_DEFAULT))"
    }
    $pk = @($pks.Rows | Where-Object { $_.TABLE_NAME -eq $name } | ForEach-Object { $_.COLUMN_NAME.ToLower() })
    if ($pk.Count -gt 0) { $defs += "  PRIMARY KEY (" + ($pk -join ", ") + ")" }
    [void]$out.AppendLine("CREATE TABLE $($name.ToLower()) (`n" + ($defs -join ",`n") + "`n);")
}

$total = 0
foreach ($t in $tables) {
    $name = $t.Name
    $ordered = $t.Group | Sort-Object { [int]$_.ORDINAL_POSITION }
    $colList = ($ordered | ForEach-Object { $_.COLUMN_NAME.ToLower() }) -join ", "
    $data = Q "SELECT * FROM [$name]"
    foreach ($r in $data.Rows) {
        $vals = foreach ($c in $ordered) { Lit $r[$c.COLUMN_NAME] $c.DATA_TYPE }
        [void]$out.AppendLine("INSERT INTO $($name.ToLower()) ($colList) OVERRIDING SYSTEM VALUE VALUES (" + ($vals -join ", ") + ");")
        $total++
    }
    $ident = $ordered | Where-Object { [int]$_.IsIdentity -eq 1 } | Select-Object -First 1
    if ($ident) {
        $tn = $name.ToLower(); $cn = $ident.COLUMN_NAME.ToLower()
        [void]$out.AppendLine("SELECT setval(pg_get_serial_sequence('$tn', '$cn'), COALESCE((SELECT MAX($cn) FROM $tn), 0) + 1, false);")
    }
}

# index ที่ใช้บ่อย
[void]$out.AppendLine("CREATE INDEX IF NOT EXISTS ix_doc_submission_doc ON doc_submission (docid, chapter, version);")
[void]$out.AppendLine("CREATE INDEX IF NOT EXISTS ix_doc_review_sub ON doc_review (sub_id);")
[void]$out.AppendLine("CREATE INDEX IF NOT EXISTS ix_permission_doc ON permission_tb (docid);")
[void]$out.AppendLine("CREATE INDEX IF NOT EXISTS ix_permission_email ON permission_tb (email);")
[void]$out.AppendLine("CREATE INDEX IF NOT EXISTS ix_talk_pair ON talk_tb (email_aj, email_ns);")
[void]$out.AppendLine("COMMIT;")

$file = Join-Path $env:TEMP "docdb_to_postgres.sql"
[IO.File]::WriteAllText($file, $out.ToString(), (New-Object Text.UTF8Encoding $false))
Write-Host "tables: $($tables.Count)  rows: $total  -> $file"

$env:PGPASSWORD = $PgPassword
$env:PGCLIENTENCODING = "UTF8"
$env:PGOPTIONS = "-c client_min_messages=warning"   # ไม่ต้องแสดง NOTICE (PowerShell มองเป็น error)
$ErrorActionPreference = "Continue"
& $Psql -h $PgHost -p $PgPort -U $PgUser -d $PgDatabase -v ON_ERROR_STOP=1 -q -f $file
if ($LASTEXITCODE -ne 0) { throw "psql failed ($LASTEXITCODE)" }
Remove-Item $file
Write-Host "done"
